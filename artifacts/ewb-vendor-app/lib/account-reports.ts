import { formatDate, formatInr, type BankAccount, type Business, type Invoice } from '@/lib/domain';
import { accountEffect, accountLabel, CASH, drCr, partyStatement, partySummaries, type Entry } from '@/lib/ledger';

/** Bank book, cash book, expenses and party ledger as PDF reports for the CA (same look as the sales report). */
export type AccountsReportKind = 'bank' | 'cash' | 'expenses' | 'ledger';
export type AccountsFilter = { from: string; to: string; kind: AccountsReportKind; /** bank account id, '' = every bank */ bankId: string; /** party key, '' = every party */ partyKey: string };

const esc = (value: string) => value.replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[c]!);
const amt = (paise: number) => (paise ? formatInr(paise) : '');
const signed = (paise: number) => `${paise < 0 ? '−' : ''}${formatInr(Math.abs(paise))}`;
const bal = (paise: number) => `${formatInr(Math.abs(paise))} ${drCr(paise)}`.trim();
const inRange = (date: string, f: { from: string; to: string }) => date >= f.from && date <= f.to;

const green = '#175b42', gold = '#f2b230', line = '#d9ddd9', soft = '#f2f7f4';
const th = (text: string, num = false) => `<th class="${num ? 'num' : ''}">${text}</th>`;

