/** What an entry says in a book: who or what, and how. */
function particulars(entry: Entry, account: string, banks: BankAccount[]) {
  if (entry.kind === 'opening') return { what: 'Opening balance', how: '' };
  if (entry.kind === 'transfer') {
    const incoming = entry.toAccount === account;
    const other = accountLabel(incoming ? entry.account : entry.toAccount ?? '', banks);
    return { what: incoming ? `Transfer from ${other}` : `Transfer to ${other}`, how: entry.reference ?? '' };
  }
  if (entry.kind === 'expense') return { what: `Expense · ${entry.category || 'Other'}${entry.note ? ` – ${entry.note}` : ''}`, how: entry.reference ?? '' };
  const party = entry.partyName || entry.note || (entry.kind === 'receipt' ? 'Received' : 'Paid');
  return {
    what: `${party}${entry.invoiceNumber ? ` (against ${entry.invoiceNumber})` : ''}${entry.partyName && entry.note ? ` – ${entry.note}` : ''}`,
    how: [account === CASH ? '' : entry.mode, entry.reference].filter(Boolean).join(' · '),
  };
}

/** One account's book for the period: opening balance, entries with running balance, closing. */
export function bookFor(entries: Entry[], account: string, f: { from: string; to: string }) {
  const mine = entries
    .filter((entry) => (entry.account === account || entry.toAccount === account) && !(entry.kind === 'opening' && !entry.account))
    .sort((a, b) => a.date.localeCompare(b.date) || a.createdAt.localeCompare(b.createdAt));
  const opening = mine.filter((entry) => entry.date < f.from).reduce((sum, entry) => sum + accountEffect(entry, account), 0);
  let balance = opening;
  let moneyIn = 0;
  let moneyOut = 0;
  const rows = mine.filter((entry) => inRange(entry.date, f)).map((entry) => {
    const effect = accountEffect(entry, account);
    balance += effect;
    if (effect > 0) moneyIn += effect; else moneyOut -= effect;
    return { entry, effect, balance };
  });
  return { opening, rows, moneyIn, moneyOut, closing: balance };
}

function bookTable(entries: Entry[], account: string, f: AccountsFilter, banks: BankAccount[]) {
  const book = bookFor(entries, account, f);
  return { book, html: `<table><thead><tr>${th('#')}${th('Date')}${th('Particulars')}${th(account === CASH ? 'Voucher no.' : 'Mode / UTR')}${th('Money in', true)}${th('Money out', true)}${th('Balance', true)}</tr></thead><tbody>
    <tr class="open"><td></td><td>${formatDate(f.from)}</td><td>Opening balance</td><td></td><td class="num"></td><td class="num"></td><td class="num">${signed(book.opening)}</td></tr>
    ${book.rows.map(({ entry, effect, balance }, index) => {
      const p = particulars(entry, account, banks);
      return `<tr><td>${index + 1}</td><td>${formatDate(entry.date)}</td><td>${esc(p.what)}</td><td>${esc(p.how)}</td><td class="num in">${effect > 0 ? formatInr(effect) : ''}</td><td class="num out">${effect < 0 ? formatInr(-effect) : ''}</td><td class="num">${signed(balance)}</td></tr>`;
    }).join('')}</tbody>
    <tfoot><tr><td colspan="4">Closing balance on ${formatDate(f.to)} (${book.rows.length} entr${book.rows.length === 1 ? 'y' : 'ies'})</td><td class="num">${formatInr(book.moneyIn)}</td><td class="num">${formatInr(book.moneyOut)}</td><td class="num">${signed(book.closing)}</td></tr></tfoot></table>` };
}

export function accountsReportHtml(business: Business | null, entries: Entry[], invoices: Invoice[], f: AccountsFilter, periodLabel: string) {
  const banks = business?.bankAccounts ?? [];

  if (f.kind === 'bank' || f.kind === 'cash') {
    const accounts = f.kind === 'cash' ? [CASH] : f.bankId ? [f.bankId] : banks.map((bank) => bank.id);
    const parts = accounts.map((account) => ({ account, ...bookTable(entries, account, f, banks) }));
    const totals = parts.reduce((sum, part) => ({ opening: sum.opening + part.book.opening, moneyIn: sum.moneyIn + part.book.moneyIn, moneyOut: sum.moneyOut + part.book.moneyOut, closing: sum.closing + part.book.closing }), { opening: 0, moneyIn: 0, moneyOut: 0, closing: 0 });
    const title = f.kind === 'cash' ? 'Cash book' : 'Bank book';
    const subtitle = `${periodLabel} · ${f.kind === 'cash' ? 'Cash in hand' : f.bankId ? accountLabel(f.bankId, banks) : 'All bank accounts'}`;
    const body = `<div class="cards">
      <div class="card">Opening balance<b>${signed(totals.opening)}</b></div>
      <div class="card">Money in<b class="in">${formatInr(totals.moneyIn)}</b></div>
      <div class="card">Money out<b class="out">${formatInr(totals.moneyOut)}</b></div>
      <div class="card">Closing balance<b>${signed(totals.closing)}</b></div>
    </div>
    ${parts.map((part) => `<h2>${esc(part.account === CASH ? 'Cash' : (() => { const bank = banks.find((item) => item.id === part.account); return bank ? `${bank.bankName} · A/c ${bank.accountNumber}${bank.ifsc ? ` · ${bank.ifsc}` : ''}` : 'Bank'; })())}</h2>${part.html}`).join('')}`;
    return frame(business, title, subtitle, body);
  }

  if (f.kind === 'expenses') {
    const list = entries.filter((entry) => entry.kind === 'expense' && inRange(entry.date, f)).sort((a, b) => a.date.localeCompare(b.date) || a.createdAt.localeCompare(b.createdAt));
    const total = list.reduce((sum, entry) => sum + entry.amountPaise, 0);
    const gst = list.reduce((sum, entry) => sum + (entry.gstPaise ?? 0), 0);
    const byCategory = new Map<string, { count: number; amount: number; gst: number }>();
    const byAccount = new Map<string, number>();
    for (const entry of list) {
      const key = entry.category || 'Other';
      const item = byCategory.get(key) ?? { count: 0, amount: 0, gst: 0 };
      item.count += 1; item.amount += entry.amountPaise; item.gst += entry.gstPaise ?? 0;
      byCategory.set(key, item);
      byAccount.set(entry.account, (byAccount.get(entry.account) ?? 0) + entry.amountPaise);
    }
    const body = `<div class="cards">
      <div class="card">Expenses<b>${list.length}</b></div>
      <div class="card">Total spent<b>${formatInr(total)}</b></div>
      <div class="card">GST input in bills<b>${formatInr(gst)}</b></div>
      ${[...byAccount.entries()].map(([account, amount]) => `<div class="card">Paid by ${esc(accountLabel(account, banks))}<b>${formatInr(amount)}</b></div>`).join('')}
    </div>
    <h2>Expenses</h2>
    ${list.length ? `<table><thead><tr>${th('#')}${th('Date')}${th('Category')}${th('Description')}${th('Paid from')}${th('Bill no.')}${th('GST', true)}${th('Amount', true)}</tr></thead><tbody>
    ${list.map((entry, index) => `<tr><td>${index + 1}</td><td>${formatDate(entry.date)}</td><td>${esc(entry.category || 'Other')}</td><td>${esc(entry.note ?? '')}</td><td>${esc(accountLabel(entry.account, banks))}</td><td>${esc(entry.reference ?? '')}</td><td class="num">${amt(entry.gstPaise ?? 0)}</td><td class="num">${formatInr(entry.amountPaise)}</td></tr>`).join('')}</tbody>
    <tfoot><tr><td colspan="6">Total (${list.length})</td><td class="num">${formatInr(gst)}</td><td class="num">${formatInr(total)}</td></tr></tfoot></table>` : '<p class="muted">No expenses in this period.</p>'}
    ${byCategory.size ? `<h2>Category-wise summary</h2><table style="width:55%"><thead><tr>${th('Category')}${th('Entries', true)}${th('GST', true)}${th('Amount', true)}</tr></thead><tbody>
    ${[...byCategory.entries()].sort((a, b) => b[1].amount - a[1].amount).map(([name, item]) => `<tr><td>${esc(name)}</td><td class="num">${item.count}</td><td class="num">${amt(item.gst)}</td><td class="num">${formatInr(item.amount)}</td></tr>`).join('')}</tbody></table>` : ''}`;
    return frame(business, 'Expense report', periodLabel, body);
  }

  // Party ledger: one party's statement, or every party's opening / debit / credit / closing.
  if (f.partyKey) {
    const statement = partyStatement(invoices, entries, f.partyKey);
    if (!statement) return frame(business, 'Party ledger', periodLabel, '<p class="muted">No entries for this party.</p>');
    const before = statement.rows.filter((row) => row.date < f.from);
    const opening = before.length ? before[before.length - 1]!.balance : 0;
    const rows = statement.rows.filter((row) => inRange(row.date, f));
    const debit = rows.reduce((sum, row) => sum + row.debit, 0);
    const credit = rows.reduce((sum, row) => sum + row.credit, 0);
    const closing = opening + debit - credit;
    const body = `<div class="cards">
      <div class="card">Party<b style="font-size:12px">${esc(statement.name)}</b><span class="muted">${esc(statement.gstin || 'Unregistered')}</span></div>
      <div class="card">Opening balance<b>${bal(opening) || formatInr(0)}</b></div>
      <div class="card">Debit (sales)<b>${formatInr(debit)}</b></div>
      <div class="card">Credit (received / purchases)<b>${formatInr(credit)}</b></div>
      <div class="card">Closing balance<b>${bal(closing) || formatInr(0)}</b><span class="muted">${closing > 0 ? 'To receive' : closing < 0 ? 'To pay' : 'Settled'}</span></div>
    </div>
    <h2>Statement of account</h2>
    <table><thead><tr>${th('#')}${th('Date')}${th('Particulars')}${th('Details')}${th('Debit', true)}${th('Credit', true)}${th('Balance', true)}</tr></thead><tbody>
    <tr class="open"><td></td><td>${formatDate(f.from)}</td><td>Opening balance</td><td></td><td class="num"></td><td class="num"></td><td class="num">${bal(opening) || formatInr(0)}</td></tr>
    ${rows.map((row, index) => `<tr><td>${index + 1}</td><td>${formatDate(row.date)}</td><td>${esc(row.title)}</td><td>${esc(row.detail)}</td><td class="num">${amt(row.debit)}</td><td class="num">${amt(row.credit)}</td><td class="num">${bal(row.balance) || formatInr(0)}</td></tr>`).join('')}</tbody>
    <tfoot><tr><td colspan="4">Closing balance on ${formatDate(f.to)}</td><td class="num">${formatInr(debit)}</td><td class="num">${formatInr(credit)}</td><td class="num">${bal(closing) || formatInr(0)}</td></tr></tfoot></table>`;
    return frame(business, 'Party ledger', `${periodLabel} · ${statement.name}`, body);
  }

  const rows = partySummaries(invoices, entries).map((summary) => {
    const statement = partyStatement(invoices, entries, summary.key)!;
    const before = statement.rows.filter((row) => row.date < f.from);
    const opening = before.length ? before[before.length - 1]!.balance : 0;
    const inPeriod = statement.rows.filter((row) => inRange(row.date, f));
    const debit = inPeriod.reduce((sum, row) => sum + row.debit, 0);
    const credit = inPeriod.reduce((sum, row) => sum + row.credit, 0);
    return { name: summary.name, gstin: summary.gstin, opening, debit, credit, closing: opening + debit - credit };
  }).filter((row) => row.opening || row.debit || row.credit).sort((a, b) => b.closing - a.closing);
  const receive = rows.reduce((sum, row) => sum + Math.max(0, row.closing), 0);
  const pay = rows.reduce((sum, row) => sum + Math.max(0, -row.closing), 0);
  const body = `<div class="cards">
    <div class="card">Parties<b>${rows.length}</b></div>
    <div class="card">To receive<b class="in">${formatInr(receive)}</b></div>
    <div class="card">To pay<b class="out">${formatInr(pay)}</b></div>
  </div>
  <h2>Party-wise outstanding</h2>
  ${rows.length ? `<table><thead><tr>${th('#')}${th('Party')}${th('GSTIN')}${th('Opening', true)}${th('Debit', true)}${th('Credit', true)}${th('Closing', true)}${th('Status')}</tr></thead><tbody>
  ${rows.map((row, index) => `<tr><td>${index + 1}</td><td>${esc(row.name)}</td><td>${esc(row.gstin || 'Unregistered')}</td><td class="num">${bal(row.opening)}</td><td class="num">${amt(row.debit)}</td><td class="num">${amt(row.credit)}</td><td class="num">${bal(row.closing) || formatInr(0)}</td><td>${row.closing > 0 ? 'To receive' : row.closing < 0 ? 'To pay' : 'Settled'}</td></tr>`).join('')}</tbody>
  <tfoot><tr><td colspan="4">Total</td><td class="num">${formatInr(rows.reduce((s, r) => s + r.debit, 0))}</td><td class="num">${formatInr(rows.reduce((s, r) => s + r.credit, 0))}</td><td class="num">${bal(receive - pay) || formatInr(0)}</td><td></td></tr></tfoot></table>` : '<p class="muted">No party entries in this period.</p>'}`;
  return frame(business, 'Party ledger', `${periodLabel} · All parties`, body);
}

/** How many entries the chosen report has (to disable the buttons when it is empty). */
export function accountsReportCount(entries: Entry[], invoices: Invoice[], f: AccountsFilter, banks: BankAccount[]) {
  if (f.kind === 'cash') return bookFor(entries, CASH, f).rows.length + (bookFor(entries, CASH, f).opening ? 1 : 0);
  if (f.kind === 'bank') return (f.bankId ? [f.bankId] : banks.map((bank) => bank.id)).reduce((sum, id) => { const book = bookFor(entries, id, f); return sum + book.rows.length + (book.opening ? 1 : 0); }, 0);
  if (f.kind === 'expenses') return entries.filter((entry) => entry.kind === 'expense' && inRange(entry.date, f)).length;
  return partySummaries(invoices, entries).filter((summary) => !f.partyKey || summary.key === f.partyKey).length;
}
